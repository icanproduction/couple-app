#!/usr/bin/env node
// Builds supabase/migrations/20261104090000_deep_talk_levels_4_5.sql from the
// ten content files in content/deep-talk-l45/<slug>.ts (shape in types.ts,
// checked by dt-l45-check.mjs). Re-run after editing the content; the SQL is
// idempotent (levels: on conflict do nothing; questions: where not exists).
//
//   node scripts/verify/build-dt-l45-migration.mjs
//
// Prints "deep talk l45 migration written" with the counts.

import fs from 'node:fs'
import path from 'node:path'
import ts from 'typescript'

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..')
const SLUGS = ['cerita-awal-kita', 'akar-keluarga', 'uang-kita', 'menuju-pelaminan', 'rumah-dan-anak', 'saat-kita-berbeda', 'bahasa-sayang', 'mimpi-berdua', 'iman-dan-nilai', 'seru-aja']
const OUT = 'supabase/migrations/20261104090000_deep_talk_levels_4_5.sql'

function literal(node, sf) {
  if (ts.isAsExpression(node) || ts.isSatisfiesExpression?.(node) || ts.isParenthesizedExpression(node)) return literal(node.expression, sf)
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) return node.text
  if (ts.isNumericLiteral(node)) return Number(node.text)
  if (node.kind === ts.SyntaxKind.NullKeyword) return null
  if (ts.isArrayLiteralExpression(node)) return node.elements.map((e) => literal(e, sf))
  if (ts.isObjectLiteralExpression(node)) {
    const o = {}
    for (const p of node.properties) if (ts.isPropertyAssignment(p)) o[p.name.getText(sf).replace(/^['"]|['"]$/g, '')] = literal(p.initializer, sf)
    return o
  }
  throw new Error(`non-literal value in ${sf.fileName}`)
}
const q = (s) => `'${String(s).replace(/'/g, "''")}'`

const levelRows = []
const questionRows = []
for (const slug of SLUGS) {
  const rel = `content/deep-talk-l45/${slug}.ts`
  const sf = ts.createSourceFile(rel, fs.readFileSync(path.join(ROOT, rel), 'utf8'), ts.ScriptTarget.Latest, true)
  let pack
  for (const st of sf.statements) if (ts.isVariableStatement(st)) for (const d of st.declarationList.declarations) if (d.name.getText(sf) === 'pack') pack = literal(d.initializer, sf)
  if (!pack || pack.slug !== slug) throw new Error(`${rel}: missing pack or slug mismatch`)
  for (const lv of pack.levels) {
    levelRows.push(`  (${q(slug)}, ${lv.level}, ${q(lv.title)}, ${q(lv.description)})`)
    lv.questions.forEach((qq, i) => questionRows.push(`  (${q(slug)}, ${lv.level}, ${i + 1}, ${q(qq.text)}, ${qq.target === null ? 'null::int' : `${qq.target}::int`})`))
  }
}

const sql = `-- Deep Talk levels 4 and 5 for all ten packs (Eric, 2026-11-04: "make the
-- deep talk level up to 5, on each topic"). 10 packs x 2 levels x 6 questions.
-- Generated by scripts/verify/build-dt-l45-migration.mjs from
-- content/deep-talk-l45/*.ts; edit the content files and re-generate, do not
-- edit this file by hand. Re-runnable: existing levels and identical questions
-- are skipped, levels 1-3 and all progress rows are untouched.

insert into public.deep_talk_levels (pack_id, level_number, title, description, question_count)
select p.id, v.level_number, v.title, v.description, 6
from (values
${levelRows.join(',\n')}
) as v(slug, level_number, title, description)
join public.deep_talk_packs p on p.slug = v.slug
on conflict (pack_id, level_number) do nothing;

insert into public.deep_talk_questions (level_id, question_text, sort_order, target_partner, is_active)
select l.id, v.question_text, v.sort_order, v.target_partner, true
from (values
${questionRows.join(',\n')}
) as v(slug, level_number, sort_order, question_text, target_partner)
join public.deep_talk_packs p on p.slug = v.slug
join public.deep_talk_levels l on l.pack_id = p.id and l.level_number = v.level_number
where not exists (
  select 1 from public.deep_talk_questions x where x.level_id = l.id and x.question_text = v.question_text
);

-- Packs created later in the admin start with five levels too ("Deepest" stays
-- the last one). Existing level rows keep their names.
create or replace function public.create_default_deep_talk_levels()
 returns trigger
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
begin
  insert into public.deep_talk_levels (pack_id, level_number, title)
  values (new.id, 1, 'Light'), (new.id, 2, 'Warmer'), (new.id, 3, 'Deeper'), (new.id, 4, 'Braver'), (new.id, 5, 'Deepest')
  on conflict (pack_id, level_number) do nothing;
  return new;
end;
$function$;
`
fs.writeFileSync(path.join(ROOT, OUT), sql)
console.log(`deep talk l45 migration written: ${OUT} (${levelRows.length} levels, ${questionRows.length} questions)`)
